"""Identity of the exact runtime input admitted by the control plane."""

from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field

RUNTIME_ATTEMPT_HEADER = "Aion-Runtime-Attempt-Id"


class RuntimeIdentity(BaseModel):
    """Frozen Version and rollout identity, shared by replicas of one input.

    The control plane assigns the attempt; it is never inferred from a request
    or generated by an agent. It identifies runtime input, not a process or an
    individual registration request.
    """

    model_config = ConfigDict(
        frozen=True, populate_by_name=True, serialize_by_alias=True)

    version_id: UUID = Field(alias="versionId")
    runtime_attempt_id: UUID = Field(alias="runtimeAttemptId")
